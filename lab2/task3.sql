--    3. Вывести в нижнем регистре все имена из таблицы продавцов, имеющие длину более 5 символов. 
-- 	    Первая буква в каждом названии должна быть удалена, а строки выведены в алфавитном порядке.


select lower(substring(name from 2 for length(name))) 
from my_schema.sal where length(name) > 5 order by name asc;
