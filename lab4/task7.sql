--    7. Вывести всю информацию о продавцах с дополнительным столбцом
--    «вид комиссии» со следующими вариантами значений: 
--    «низкая», если комиссионные меньше 0.12,
--    «средняя», если комиссионные от 0.12 до 0.13,
--    «высокая», если комиссионные больше 0.13.  

select *,
  case
    when comm < 0.12 then 'низкая'
    when comm >= 0.12 and comm <= 0.13 then 'средняя'
    else 'высокая'
  end as "вид комиссии"
from my_schema.sal;
